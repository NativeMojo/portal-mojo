import React from 'react';
import { createRoot } from 'react-dom/client';
import { QueryClient, QueryClientProvider } from '@tanstack/react-query';
import { HashRouter } from 'react-router-dom';
import { initAuth, setTokens } from '../../packages/portal-mojo/src/client/runtime';
import { setActiveGroupSignal } from '../../packages/portal-mojo/src/client/active-group';
import { openMemberAdmissionDialog } from '../../packages/portal-mojo/src/admin/identity/members/member-flows';
import { MemberDetail } from '../../packages/portal-mojo/src/admin/identity/members/MemberDetail';
import { MemberModel } from '../../packages/portal-mojo/src/admin/identity/members/models';
import { ModalHost, modal, toast } from '../../packages/portal-mojo/src/ui';
import 'bootstrap-icons/font/bootstrap-icons.css';
import '../../apps/portal/src/theme.css';
const qc = new QueryClient({ defaultOptions: { queries: { retry: false, staleTime: Infinity }, mutations: { retry: false, gcTime: 0 } } });
const token = (id: number) => `e30.${btoa(JSON.stringify({ uid: id, exp: Date.now() / 1000 + 3600, iat: Date.now() / 1000 }))}.mock`;
initAuth(); setTokens(token(1)); setActiveGroupSignal(10);
const notices: string[] = [];
toast.success = message => { notices.push(message); };
toast.error = message => { notices.push(message); };
let created = 0, invalidations = 0;
const owner = new AbortController();
const invalidate = qc.invalidateQueries.bind(qc);
qc.invalidateQueries = (...args) => { invalidations++; return invalidate(...args); };
const open = () => openMemberAdmissionDialog({ group: { id: 10, name: 'Fixture fleet', kind: 'fleet' }, canInvite: true, canCreate: true, canReadUsers: true, initialMode: 'invite', roles: [{ value: 'operator', label: 'Operator', permissions: ['manage_kiosks'] }], queryClient: qc, signal: owner.signal, onCreated: () => { created++; } });
Object.assign(window, { fixture: { open, switchAccount: () => setTokens(token(2)), switchGroup: () => setActiveGroupSignal(20), switchBack: () => { setTokens(token(1)); setActiveGroupSignal(10); }, abortOwner: () => owner.abort(), close: () => modal.closeAll(), detail: () => modal.detail(close => <MemberDetail id={103} ownerSignal={owner.signal} onClose={() => close(null)} />), state: () => ({ notices, created, invalidations, cached: qc.getQueryData(MemberModel.keys.one(103)) }) } });
createRoot(document.getElementById('root')!).render(<QueryClientProvider client={qc}><HashRouter><button onClick={() => void open()}>Invite fixture</button><ModalHost /></HashRouter></QueryClientProvider>);
